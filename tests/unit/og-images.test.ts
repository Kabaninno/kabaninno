import { readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { locales } from '@/i18n/routing';
import { OG_IMAGE_SIZE, ogImagePath } from '@/lib/metadata';

const PUBLIC = join(process.cwd(), 'public');

/** Width and height from a PNG's IHDR chunk. */
function pngSize(file: string): { width: number; height: number } {
  const bytes = readFileSync(file);
  expect(bytes.subarray(1, 4).toString('latin1')).toBe('PNG');
  return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
}

/*
 * The Open Graph images are static files generated by `npm run og:images`
 * (scripts/og-images.mjs) and committed; metadata points at them.
 */
describe('Open Graph images', () => {
  for (const locale of locales) {
    it(`${ogImagePath(locale)} exists, is ${OG_IMAGE_SIZE.width}×${OG_IMAGE_SIZE.height} and light`, () => {
      const file = join(PUBLIC, ogImagePath(locale));
      expect(pngSize(file)).toEqual(OG_IMAGE_SIZE);
      expect(statSync(file).size).toBeLessThan(300 * 1024);
    });
  }
});
