import type { Metadata } from 'next';
import { siteConfig } from '~/site.config';
import { getMessagesFor } from '@/i18n/messages';
import { defaultLocale, locales, type Locale } from '@/i18n/routing';
import { fillTemplate } from './portfolio';
import { absoluteUrl } from './site-url';

export const OG_LOCALE: Record<Locale, string> = { pl: 'pl_PL', en: 'en_US', uk: 'uk_UA' };

/** Size of the Open Graph images (`public/og/<locale>.png`, `scripts/og-images.mjs`). */
export const OG_IMAGE_SIZE = { width: 1200, height: 630 } as const;

/** Root-relative path of a locale's Open Graph image. */
export function ogImagePath(locale: Locale): string {
  return `/og/${locale}.png`;
}

/**
 * The locale's Open Graph image: a static PNG in `public/og/` (generated by
 * `npm run og:images`, committed), referenced by an absolute URL that
 * includes the base path, so it also works for GitHub Pages project sites.
 */
export function ogImage(locale: Locale) {
  return {
    url: absoluteUrl(ogImagePath(locale)),
    ...OG_IMAGE_SIZE,
    type: 'image/png',
    alt: fillTemplate(getMessagesFor(locale).meta.ogImageAlt, { studio: siteConfig.studioName }),
  };
}

/** Locale-prefixed path, e.g. ("pl", "/services/web/") → "/pl/services/web/". */
export function localizedPath(locale: Locale, path: string): string {
  return `/${locale}${path === '/' ? '/' : path}`;
}

/** hreflang map for one locale-less path, including x-default. */
export function languageAlternates(path: string): Record<string, string> {
  const entries = locales.map((locale) => [locale, absoluteUrl(localizedPath(locale, path))]);
  return {
    ...Object.fromEntries(entries),
    'x-default': absoluteUrl(localizedPath(defaultLocale, path)),
  };
}

interface PageMetadataInput {
  locale: Locale;
  /** Locale-less path with trailing slash, e.g. "/services/web/". */
  path: string;
  title: string;
  description: string;
  /** Use the title as-is (no " · Studio" suffix from the template). */
  absoluteTitle?: boolean;
  noIndex?: boolean;
}

export function buildPageMetadata({
  locale,
  path,
  title,
  description,
  absoluteTitle = false,
  noIndex = false,
}: PageMetadataInput): Metadata {
  const url = absoluteUrl(localizedPath(locale, path));
  const image = ogImage(locale);
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: url, languages: languageAlternates(path) },
    openGraph: {
      type: 'website',
      url,
      title,
      description,
      siteName: siteConfig.studioName,
      locale: OG_LOCALE[locale],
      alternateLocale: locales.filter((l) => l !== locale).map((l) => OG_LOCALE[l]),
      images: [image],
    },
    twitter: {
      card: 'summary_large_image',
      title,
      description,
      images: [{ url: image.url, alt: image.alt }],
    },
    ...(noIndex ? { robots: { index: false, follow: true } } : {}),
  };
}
